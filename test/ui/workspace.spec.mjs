test('failed saves preserve the form and draft for retry', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: '新建任务' }).click();
  await page.getByLabel('任务标题').fill('不能丢失的草稿');
  await page.route('**/api/commands', route => route.abort('failed'));
  await page.getByRole('button', { name: '创建任务', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByLabel('任务标题')).toHaveText('不能丢失的草稿');
  await expect(page.getByRole('alert')).toContainText('暂时无法保存');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '新建任务' }).click();
  await expect(page.getByLabel('任务标题')).toHaveText('不能丢失的草稿');
});

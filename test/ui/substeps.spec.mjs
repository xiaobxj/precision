import { test, expect } from '@playwright/test';
import { localDay } from '../../lib/domain.mjs';

async function seed(page, title) {
  let state = await (await page.request.get('/api/state')).json();
  const run = async command => {
    const response = await page.request.post('/api/commands', { data: { revision: state.revision, command } });
    expect(response.ok()).toBeTruthy(); state = await response.json();
  };
  await run({ type: 'create-task', title, date: localDay() });
  const taskId = state.tasks.at(-1).id;
  await run({ type: 'create-step', taskId, title: '中心调整方向', content: '原来的进度内容保留', status: 'done' });
  await run({ type: 'create-step', taskId, title: '独立验证方向', status: 'done' });
  return taskId;
}

async function removeTask(page, taskId) {
  const state = await (await page.request.get('/api/state')).json();
  const response = await page.request.post('/api/commands', { data: { revision: state.revision, command: { type: 'delete-task', taskId } } });
  expect(response.ok()).toBeTruthy();
}


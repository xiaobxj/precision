test('child drafts survive failed saves and a stale editor preserves both the saved record and unsaved input', async ({ page, context }) => {
  const taskId = await seed(page, '子进度草稿测试');
  await page.goto('/');
  const direction = page.locator(`[data-task-id="${taskId}"] .step`).first();
  await direction.getByRole('button', { name: '添加子进度', exact: true }).click();
  await page.getByLabel('子进度标题').fill('不会丢失的子进度');
  await page.getByLabel('进度记录').fill('保存失败也保留输入');
  await page.route('**/api/commands', route => route.abort('failed'));
  await page.getByRole('dialog').getByRole('button', { name: '添加子进度', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('暂时无法保存');
  await page.reload();
  await page.unroute('**/api/commands');
  await direction.getByRole('button', { name: '添加子进度', exact: true }).click();
  await expect(page.getByLabel('子进度标题')).toHaveText('不会丢失的子进度');
  await expect(page.getByLabel('进度记录')).toHaveText('保存失败也保留输入');
  await page.getByRole('dialog').getByRole('button', { name: '添加子进度', exact: true }).click();
  await direction.getByRole('button', { name: '编辑子进度', exact: true }).click();
  await page.getByLabel('进度记录').fill('窗口 A 的草稿');
  const other = await context.newPage(); await other.goto('/');
  await other.locator(`[data-task-id="${taskId}"]`).getByRole('button', { name: '编辑子进度', exact: true }).click();
  await other.getByLabel('进度记录').fill('窗口 B 已保存');
  await other.getByRole('button', { name: '保存修改', exact: true }).click();
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('其他窗口更新了内容');
  await expect(page.getByLabel('进度记录')).toHaveText('窗口 A 的草稿');
  const saved = await (await page.request.get('/api/state')).json();
  expect(saved.tasks.find(task => task.id === taskId).steps[0].substeps[0].content).toBe('窗口 B 已保存');
  await removeTask(page, taskId);
});

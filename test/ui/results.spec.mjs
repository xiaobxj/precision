test('result drafts survive reload, stay separate from child drafts and do not overwrite another window', async ({ page, context }) => {
  const { taskId } = await seed(page, '结果草稿保护测试');
  await page.goto('/');
  const task = page.locator(`[data-task-id="${taskId}"]`);
  await task.getByRole('button', { name: '记录结果', exact: true }).click();
  await page.getByLabel('结果标题').fill('不能丢失的结果');
  await page.getByLabel('结果内容').fill('保存失败时保留的结果正文');
  await page.route('**/api/commands', route => route.abort('failed'));
  await page.getByRole('button', { name: '保存结果', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('暂时无法保存');
  await page.reload();
  await page.unroute('**/api/commands');
  await task.getByRole('button', { name: '添加子进度', exact: true }).click();
  await expect(page.getByLabel('子进度标题')).toBeEmpty();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await task.getByRole('button', { name: '记录结果', exact: true }).click();
  await expect(page.getByLabel('结果标题')).toHaveText('不能丢失的结果');
  await expect(page.getByLabel('结果内容')).toHaveText('保存失败时保留的结果正文');
  await page.getByRole('button', { name: '保存结果', exact: true }).click();
  await task.getByRole('button', { name: '编辑结果', exact: true }).click();
  await page.getByLabel('结果内容').fill('窗口 A 的结果草稿');
  const other = await context.newPage(); await other.goto('/');
  await other.locator(`[data-task-id="${taskId}"]`).getByRole('button', { name: '编辑结果', exact: true }).click();
  await other.getByLabel('结果内容').fill('窗口 B 已保存的结果');
  await other.getByRole('button', { name: '保存修改', exact: true }).click();
  await page.getByRole('button', { name: '保存修改', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('其他窗口更新了内容');
  await expect(page.getByLabel('结果内容')).toHaveText('窗口 A 的结果草稿');
  const state = await (await page.request.get('/api/state')).json();
  expect(state.tasks.find(task => task.id === taskId).steps[0].results[0].content).toBe('窗口 B 已保存的结果');
  await removeTask(page, taskId);
});
